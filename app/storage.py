"""All filesystem reads and writes live here.

Ids and filenames are uuid4 hex values generated by this module. Anything that
arrives from a request is checked against a strict pattern before any path is
built, so user input can never become part of a path.
"""

import json
import os
import re
import uuid
from datetime import datetime, timezone
from pathlib import Path

from .presets import SECTION_ORDER

ID_RE = re.compile(r"^[0-9a-f]{32}$")
FILENAME_RE = re.compile(r"^[0-9a-f]{32}\.png$")

JSON_NAME = "storyboard.json"


def _now():
    return datetime.now(timezone.utc).isoformat()


def _new_id():
    return uuid.uuid4().hex


def _storyboard_dir(data_dir, storyboard_id):
    """Return the folder for a storyboard id, or None if the id is not valid."""
    if not is_valid_id(storyboard_id):
        return None
    return Path(data_dir) / storyboard_id


def _write_json_atomic(path, data):
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(json.dumps(data, indent=2), encoding="utf-8")
    os.replace(tmp, path)


def ensure_data_dir(data_dir):
    Path(data_dir).mkdir(parents=True, exist_ok=True)


def load_storyboard(data_dir, storyboard_id):
    """Return the storyboard dict, or None if the id is invalid or missing."""
    folder = _storyboard_dir(data_dir, storyboard_id)
    if folder is None:
        return None
    path = folder / JSON_NAME
    if not path.is_file():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def list_storyboards(data_dir):
    """All storyboards, newest first."""
    boards = []
    root = Path(data_dir)
    if not root.is_dir():
        return boards
    for child in root.iterdir():
        if child.is_dir():
            board = load_storyboard(data_dir, child.name)
            if board is not None:
                boards.append(board)
    boards.sort(key=lambda b: b["created"], reverse=True)
    return boards


def create_storyboard(data_dir, song_title):
    board = {
        "id": _new_id(),
        "song_title": song_title,
        "created": _now(),
        "frames": [],
    }
    folder = _storyboard_dir(data_dir, board["id"])
    folder.mkdir(parents=True)
    _write_json_atomic(folder / JSON_NAME, board)
    return board


def sorted_frames(board):
    """Frames in storyboard order: section order, then created time."""
    def key(frame):
        try:
            idx = SECTION_ORDER.index(frame["section"])
        except ValueError:
            idx = len(SECTION_ORDER)
        return (idx, frame["created"])

    return sorted(board["frames"], key=key)


def new_id():
    """A fresh uuid4 hex id (for callers that need a frame id before saving)."""
    return _new_id()


def is_valid_id(value):
    # fullmatch: ID_RE's "$" would also accept a trailing newline.
    return isinstance(value, str) and ID_RE.fullmatch(value) is not None


def is_valid_filename(value):
    return isinstance(value, str) and FILENAME_RE.fullmatch(value) is not None


def add_frame(data_dir, storyboard_id, fields, png_bytes, frame_id=None):
    """Save the PNG, then record the frame in storyboard.json.

    fields: section, scene, camera, shot, lighting, direction, fx, prompt.
    frame_id: optional pre-minted id (the fx seed comes from it); must be a
    32-char lowercase hex id or ValueError is raised before anything is written.
    If recording fails, the PNG is removed so no orphan file is left behind.
    """
    if frame_id is not None and not is_valid_id(frame_id):
        raise ValueError("Invalid frame id")
    board = load_storyboard(data_dir, storyboard_id)
    if board is None:
        raise FileNotFoundError(storyboard_id)
    folder = _storyboard_dir(data_dir, storyboard_id)
    frame = dict(fields)
    frame["id"] = frame_id if frame_id is not None else _new_id()
    frame["filename"] = _new_id() + ".png"
    frame["created"] = _now()
    image_path = folder / frame["filename"]
    image_path.write_bytes(png_bytes)
    try:
        board["frames"].append(frame)
        _write_json_atomic(folder / JSON_NAME, board)
    except Exception:
        image_path.unlink(missing_ok=True)
        raise
    return frame


TRASH_DIR = "_trash"


def _trash_target(data_dir, kind, suffix):
    """A fresh, never-colliding folder under data/_trash/<kind>/ (created lazily)."""
    parent = Path(data_dir) / TRASH_DIR / kind
    parent.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
    base = f"{stamp}_{suffix}"
    target = parent / base
    n = 0
    while target.exists():
        n += 1
        target = parent / f"{base}-{n}"
    return target


def rename_storyboard(data_dir, storyboard_id, new_title):
    """Set a new song title (caller validates it). Returns False if the tape is missing."""
    board = load_storyboard(data_dir, storyboard_id)
    if board is None:
        return False
    board["song_title"] = new_title
    _write_json_atomic(_storyboard_dir(data_dir, storyboard_id) / JSON_NAME, board)
    return True


def trash_storyboard(data_dir, storyboard_id):
    """Soft delete: move the whole tape folder into data/_trash/tapes/. False if missing."""
    if load_storyboard(data_dir, storyboard_id) is None:
        return False
    folder = _storyboard_dir(data_dir, storyboard_id)
    target = _trash_target(data_dir, "tapes", storyboard_id)
    os.replace(folder, target)
    return True


def trash_frame(data_dir, storyboard_id, frame_id):
    """Soft delete one frame: image + a frame.json record go to data/_trash/frames/.

    Order: stage the image and record in trash, then atomically rewrite the
    tape JSON; if that fails, put the image back. False if tape or frame is missing.
    Frame order needs no renumbering: it is derived from (section, created).
    """
    if not is_valid_id(frame_id):
        return False
    board = load_storyboard(data_dir, storyboard_id)
    if board is None:
        return False
    frame = next((f for f in board["frames"] if f.get("id") == frame_id), None)
    if frame is None:
        return False
    folder = _storyboard_dir(data_dir, storyboard_id)
    image = folder / frame["filename"]
    target = _trash_target(data_dir, "frames", f"{storyboard_id}_{frame_id}")
    target.mkdir()
    moved = False
    try:
        (target / "frame.json").write_text(
            json.dumps({"storyboard_id": storyboard_id, "frame": frame}, indent=2),
            encoding="utf-8")
        if image.is_file():
            os.replace(image, target / frame["filename"])
            moved = True
        board["frames"] = [f for f in board["frames"] if f.get("id") != frame_id]
        _write_json_atomic(folder / JSON_NAME, board)
    except Exception:
        if moved:
            os.replace(target / frame["filename"], image)
        (target / "frame.json").unlink(missing_ok=True)
        try:
            target.rmdir()
        except OSError:
            pass
        raise
    _trash_clip_files(folder / CLIPS_DIR, frame_id, target)
    return True


def _trash_clip_files(clips, frame_id, target):
    """Best effort: a clip the browser still holds open must not block erasing the frame."""
    for path in clips.glob(f"{frame_id}.*"):
        try:
            os.replace(path, target / path.name)
        except OSError:
            pass


# ---- animated clips: data/<tape>/clips/ ----------------------------------------
# Every clip is written under a NEW name (<key>.<fingerprint12>.mp4) because
# Windows will not replace a file a browser has open. <key>.json is the commit
# marker: it names the current clip file and the fingerprint it was made from.

CLIPS_DIR = "clips"
TAPE_KEY = "tape"
FRAME_CLIP_RE = re.compile(r"^[0-9a-f]{32}\.[0-9a-f]{12}\.mp4$")
TAPE_CLIP_RE = re.compile(r"^tape\.[0-9a-f]{12}\.mp4$")
# An imported AI clip uses the key "<frame_id>.ai": clips/<frame_id>.ai.<fp12>.mp4 + <frame_id>.ai.json
AI_SUFFIX = ".ai"
AI_CLIP_RE = re.compile(r"^[0-9a-f]{32}\.ai\.[0-9a-f]{12}\.mp4$")
CLIP_SOURCES = ("procedural", "ai")


def ai_key(frame_id):
    return frame_id + AI_SUFFIX


def _is_ai_key(key):
    return isinstance(key, str) and key.endswith(AI_SUFFIX) and is_valid_id(key[:-len(AI_SUFFIX)])


def _clip_key_ok(key):
    return key == TAPE_KEY or is_valid_id(key) or _is_ai_key(key)


def _clip_pattern(key):
    if key == TAPE_KEY:
        return TAPE_CLIP_RE
    return AI_CLIP_RE if _is_ai_key(key) else FRAME_CLIP_RE


def set_camera_move(data_dir, storyboard_id, frame_id, move):
    """Store a frame's camera move (caller validates it). False if tape or frame is missing."""
    if not is_valid_id(frame_id):
        return False
    board = load_storyboard(data_dir, storyboard_id)
    if board is None:
        return False
    frame = next((f for f in board["frames"] if f.get("id") == frame_id), None)
    if frame is None:
        return False
    if frame.get("camera_move") != move:
        frame["camera_move"] = move
        _write_json_atomic(_storyboard_dir(data_dir, storyboard_id) / JSON_NAME, board)
    return True


def set_clip_source(data_dir, storyboard_id, frame_id, source):
    """Store which clip Play tape uses for a frame: "ai" or "procedural" (caller validates)."""
    if not is_valid_id(frame_id) or source not in CLIP_SOURCES:
        return False
    board = load_storyboard(data_dir, storyboard_id)
    if board is None:
        return False
    frame = next((f for f in board["frames"] if f.get("id") == frame_id), None)
    if frame is None:
        return False
    if frame.get("clip_source") != source:
        frame["clip_source"] = source
        _write_json_atomic(_storyboard_dir(data_dir, storyboard_id) / JSON_NAME, board)
    return True


def trash_ai_clip(data_dir, storyboard_id, frame_id):
    """Soft delete a frame's AI clip: its files go to data/_trash/ai-clips/, the frame falls
    back to the procedural clip. False if the tape or frame is missing.

    The commit marker moves first (so the clip stops existing at once; a failure there
    raises and changes nothing). The video itself is best effort, because a browser
    may hold it open on Windows; a leftover is cleaned up by the next import.
    """
    if not is_valid_id(frame_id) or load_storyboard(data_dir, storyboard_id) is None:
        return False
    if not set_clip_source(data_dir, storyboard_id, frame_id, "procedural"):
        return False
    clips = _storyboard_dir(data_dir, storyboard_id) / CLIPS_DIR
    key = ai_key(frame_id)
    marker = clips / f"{key}.json"
    target = _trash_target(data_dir, "ai-clips", f"{storyboard_id}_{frame_id}")
    if marker.is_file() or any(clips.glob(f"{key}.*")):
        target.mkdir()
        if marker.is_file():
            os.replace(marker, target / marker.name)
        for path in clips.glob(f"{key}.*"):
            try:
                os.replace(path, target / path.name)
            except OSError:
                pass
    return True


def read_clip_meta(data_dir, storyboard_id, key):
    folder = _storyboard_dir(data_dir, storyboard_id)
    if folder is None or not _clip_key_ok(key):
        return None
    try:
        meta = json.loads((folder / CLIPS_DIR / f"{key}.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return meta if isinstance(meta, dict) else None


def clip_file_path(data_dir, storyboard_id, key, meta):
    """Path to the clip file the meta names, only if the name is strictly well-formed."""
    folder = _storyboard_dir(data_dir, storyboard_id)
    name = meta.get("file")
    pattern = _clip_pattern(key) if _clip_key_ok(key) else FRAME_CLIP_RE
    if (folder is None or not _clip_key_ok(key) or not isinstance(name, str)
            or pattern.fullmatch(name) is None or not name.startswith(key + ".")):
        return None
    path = folder / CLIPS_DIR / name
    return path if path.is_file() else None


def new_clip_tmp(data_dir, storyboard_id, key):
    """A fresh temp path inside the tape's clips folder. Its .tmp name is never served."""
    folder = _storyboard_dir(data_dir, storyboard_id)
    if folder is None or not _clip_key_ok(key):
        raise ValueError("Invalid clip key")
    clips = folder / CLIPS_DIR
    clips.mkdir(exist_ok=True)
    return clips / f"{key}.{_new_id()}.tmp"


def commit_clip(data_dir, storyboard_id, key, tmp, fingerprint, info=None):
    """Publish a finished temp file: move to its fingerprinted name, then write the meta.

    The old file is never touched until the new one is committed; leftovers are
    then removed best-effort.
    """
    clips = tmp.parent
    name = f"{key}.{fingerprint[:12]}.mp4"
    final = clips / name
    if final.exists():  # same fingerprint means identical content; keep the existing file
        tmp.unlink(missing_ok=True)
    else:
        os.replace(tmp, final)
    meta = {"fingerprint": fingerprint, "file": name, "created": _now(), **(info or {})}
    _write_json_atomic(clips / f"{key}.json", meta)
    cleanup_old_clips(clips, key, name)
    return meta


def cleanup_old_clips(clips, key, keep):
    """Delete superseded clip files; a locked file is skipped and retried next time."""
    pattern = _clip_pattern(key)
    for path in clips.glob(f"{key}.*.mp4"):
        # A frame's glob <id>.*.mp4 also matches its AI clip <id>.ai.<fp>.mp4; the strict
        # pattern keeps each kind of clip from cleaning up the other.
        if path.name == keep or pattern.fullmatch(path.name) is None:
            continue
        try:
            os.remove(path)
        except OSError:
            pass


def frame_image_path(data_dir, storyboard_id, filename):
    """Path to a frame image, or None.

    Validates both names first, and only returns files that this storyboard's
    own frame list references (so a real filename under the wrong storyboard
    id is not found).
    """
    if not is_valid_filename(filename):
        return None
    board = load_storyboard(data_dir, storyboard_id)
    if board is None:
        return None
    if not any(f["filename"] == filename for f in board["frames"]):
        return None
    path = _storyboard_dir(data_dir, storyboard_id) / filename
    return path if path.is_file() else None
